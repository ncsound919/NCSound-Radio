#!/usr/bin/env node
/**
 * rotate-icecast-credentials.cjs
 *
 * Generates strong Icecast credentials and writes them to infra/icecast/.env,
 * which .gitignore already excludes (rule `.env`, line 12) while
 * `infra/icecast/.env.example` stays tracked (negation `!.env.example`, line 14).
 *
 * The values are written straight to disk and are NEVER printed. That is the
 * whole point: a rotation whose new secret appears in a terminal transcript has
 * moved the exposure rather than closed it. This is the defect recorded against
 * the Stripe key in 2026-09-28-ecosystem-content-aetherdesk-exam.
 *
 * Icecast's XML config has no environment substitution, so the template carries
 * __ICECAST_*__ placeholders and station-up.sh renders them at copy time. That
 * injection point already existed at station-up.sh:38 (`cp` into
 * /etc/icecast2/icecast.xml).
 *
 * Usage: node rotate-icecast-credentials.cjs [--force]
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const INFRA = path.join(__dirname, '..', 'infra');
const ICE = path.join(INFRA, 'icecast');
const ENV_PATH = path.join(ICE, '.env');
const EXAMPLE_PATH = path.join(ICE, '.env.example');

const force = process.argv.includes('--force');

// 32 hex chars from the OS CSPRNG. No ambiguous-subset trimming, because a
// password does not need to be memorable and every trimming rule shortens the
// space for no operational benefit.
const gen = () => crypto.randomBytes(16).toString('hex');

if (fs.existsSync(ENV_PATH) && !force) {
  console.error(`refusing to overwrite ${ENV_PATH} (pass --force to rotate again)`);
  process.exit(1);
}

const creds = {
  ICECAST_SOURCE_PASSWORD: gen(),
  ICECAST_ADMIN_PASSWORD: gen(),
  HARBOR_PASSWORD: gen(),
  LIVE_HARBOR_PASSWORD: gen(),
};

const body = [
  '# Icecast + Harbor credentials for NCSound Radio.',
  '# GENERATED by infra/rotate-icecast-credentials.cjs. Not tracked by git.',
  '#',
  '# Icecast XML cannot read the environment, so infra/icecast/icecast.xml is a',
  '# TEMPLATE carrying __ICECAST_SOURCE_PASSWORD__ / __ICECAST_ADMIN_PASSWORD__ and',
  '# infra/station-up.sh renders them into /etc/icecast2/icecast.xml at copy time.',
  '# Liquidsoap and the verify scripts read these directly.',
  '#',
  '# Rotating all four together is mandatory: changing the source password',
  '# without changing ncsound.liq leaves Liquidsoap authenticating with a stale',
  '# password, the mount goes silent, and Icecast reports the mount as healthy',
  '# with no source on it. Restart both daemons together (station-down.sh then',
  '# station-up.sh) or do not rotate.',
  '',
  `ICECAST_SOURCE_PASSWORD=${creds.ICECAST_SOURCE_PASSWORD}`,
  `ICECAST_ADMIN_PASSWORD=${creds.ICECAST_ADMIN_PASSWORD}`,
  `HARBOR_PASSWORD=${creds.HARBOR_PASSWORD}`,
  `LIVE_HARBOR_PASSWORD=${creds.LIVE_HARBOR_PASSWORD}`,
  '',
].join('\n');

fs.writeFileSync(ENV_PATH, body, { mode: 0o600 });

// The tracked template. Values are placeholders, never real ones.
const example = [
  '# Contract for infra/icecast/.env. Copy to .env and fill in.',
  '#   cp infra/icecast/.env.example infra/icecast/.env && chmod 600 infra/icecast/.env',
  '# Or generate a fresh set:  node infra/rotate-icecast-credentials.cjs',
  '',
  '# Password Liquidsoap uses to authenticate the SOURCE mounts (live.mp3, mobile.mp3).',
  '# Must equal <source-password> in icecast.xml after rendering.',
  'ICECAST_SOURCE_PASSWORD=replace-with-32-hex-chars',
  '',
  '# Password for Icecast admin endpoints (/admin/listmounts, /admin/stats,',
  '# status-json.xsl). Must equal <admin-password> in icecast.xml after rendering.',
  'ICECAST_ADMIN_PASSWORD=replace-with-32-hex-chars',
  '',
  '# Password for the Harbor ingest endpoint on 127.0.0.1:8008/dj, which the DJ',
  '# engine pushes audio into. Must equal the password in ncsound.liq.',
  'HARBOR_PASSWORD=replace-with-32-hex-chars',
  '',
  '# Password for the LIVE harbor mount on 127.0.0.1:8008/live, which the DJ',
  '# console reaches through ingest (ingest -> ffmpeg -> this mount). Must equal',
  '# the password in ncsound.liq. Rotate with the others and restart both daemons.',
  'LIVE_HARBOR_PASSWORD=replace-with-32-hex-chars',
  '',
].join('\n');
fs.writeFileSync(EXAMPLE_PATH, example);

// Prove the file is actually ignored rather than assuming it.
const { execFileSync } = require('node:child_process');
let ignored = false;
try {
  execFileSync('git', ['check-ignore', '-q', path.relative(process.cwd(), ENV_PATH)], { stdio: 'ignore' });
  ignored = true;
} catch { ignored = false; }

console.log(`wrote ${ENV_PATH}`);
console.log(`wrote ${ENV_PATH.replace('.env', '.env.example')} (template, placeholders only)`);
console.log(`gitignored: ${ignored ? 'YES' : 'NO -- DO NOT COMMIT THIS FILE'}`);
console.log('values were not printed. read the file directly if you need them.');
if (!ignored) process.exit(1);